"""Compile the pinned NVIDIA shader offline and embed its Direct3D bytecode.

Requires the Windows SDK FXC compiler only when regenerating this artifact.
Game builds and runtime use the checked-in bytecode and need no shader compiler.
"""

import argparse
import hashlib
import os
import subprocess
import tempfile
from pathlib import Path

COMMON = Path(__file__).resolve().parents[1]
SOURCE = COMMON / "third_party/nis"
OUTPUT = COMMON / "src/ipod/platform/sdl3/nis_shader.inc"
DEFINES = (
    "NIS_THREAD_GROUP_SIZE=128",
    "NIS_BLOCK_WIDTH=32",
    "NIS_BLOCK_HEIGHT=24",
    "NIS_VIEWPORT_SUPPORT=1",
    "NIS_CLAMP_OUTPUT=1",
)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--fxc", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    compiler = args.fxc
    if compiler is None:
        kits = Path(os.environ.get("ProgramFiles(x86)", "C:/Program Files (x86)"))
        candidates = sorted((kits / "Windows Kits/10/bin").glob("*/x64/fxc.exe"))
        if not candidates:
            raise SystemExit("Pass --fxc pointing to the Windows SDK x64 fxc.exe")
        compiler = candidates[-1]
    with tempfile.TemporaryDirectory(prefix="ipod-nis-") as temporary:
        binary = Path(temporary) / "nis.cso"
        command = [
            str(compiler),
            "/nologo",
            "/T",
            "cs_5_0",
            "/E",
            "main",
            "/O3",
            "/Qstrip_debug",
            "/Qstrip_reflect",
            "/Fo",
            str(binary),
        ]
        for define in DEFINES:
            command += ["/D", define]
        command += [str(SOURCE / "NIS_Main.hlsl")]
        subprocess.run(command, check=True, capture_output=True)
        bytecode = binary.read_bytes()
    digest = hashlib.sha256(bytecode).hexdigest()
    result = "// Generated by common/tools/embed_nis.py; NVIDIA MIT license in common/third_party/nis.\n"
    result += (
        f"// Bytecode SHA-256: {digest}\nstatic const unsigned char nis_shader[] = {{\n"
    )
    result += (
        "\n".join(
            "    " + ", ".join(f"0x{byte:02x}" for byte in bytecode[i : i + 16]) + ","
            for i in range(0, len(bytecode), 16)
        )
        + "\n};\n"
    )
    if args.check:
        if OUTPUT.read_text(encoding="utf-8") != result:
            raise SystemExit(
                "NIS bytecode differs; regenerate with the documented FXC version"
            )
    else:
        OUTPUT.write_text(result, encoding="utf-8")
    print(f"NIS bytecode: {len(bytecode)} bytes, SHA-256 {digest}")


if __name__ == "__main__":
    main()
